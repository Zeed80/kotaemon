#!/bin/bash
# Скрипт для безопасного обновления из репозитория с отбрасыванием локальных изменений

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_ROOT}"

echo "Обновление из репозитория..."
echo "Все локальные изменения будут отброшены."

# Отбросить все локальные изменения
git reset --hard HEAD

# Обновить из удаленного репозитория
git pull

echo "Обновление завершено."
